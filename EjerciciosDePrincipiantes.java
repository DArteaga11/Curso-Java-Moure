public class EjerciciosDePrincipiantes {

    public static void main(String[] args) {

        // 1. Declara una variable de tipo String y asígnale tu nombre
        String nombre = "Daniel Arteaga" ;
        System.out.println(nombre);
        // 2. Crea una variable de tipo int y asígnale tu edad
        int edad = 23;
        System.out.println(edad);
        // 3. Crea una variable doublé con tu altura en metros
        double altura = 1.80;
        System.out.println(altura);
        // 4. Declara una variable de tipo boolean que indique si te gusta programar
        boolean programar = true;
        System.out.println(programar);
        // 5. Declara una constante con tu email
        final String CORREO = "danielpacgik@gmail.com";
        System.out.println(CORREO);
        // 6. Crea una variable de tipo char y guárdale tu inicial
        char inicial = 'D';
        System.out.println(inicial);
        // 7. Declara una variable de tipo String con tu localidad a continuación cambia su valor y vuelve a imprimir
        String localidad = "Iztapalapa";
        System.out.println(localidad);
        localidad = "Iztacalco";
        System.out.println(localidad);
        // 8. Crea una variable de int llamada a, otra b, e imprime la suma de ambas
        int a = 10;
        int b = 10;
        System.out.println(("El resultad de la suma es: ") + (a + b));

        // 9. Intenta declara una variable sin inicializarla y luego asígnale un valor antes de imprimirla
        String apellido;
        apellido = "Arteaga";
        System.out.println(apellido);
    }
}
